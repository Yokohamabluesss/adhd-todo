import assert from 'node:assert/strict';

export async function checkLanguage(browser,url='http://127.0.0.1:4174/') {
  const context = await browser.newContext({viewport:{width:390,height:844}});
  try {
    const page = await context.newPage();
    page.setDefaultTimeout(5000);
    const errors = [];
    page.on('pageerror',error=>errors.push(error.message));
    const button = name => page.getByRole('button',{name,exact:true});
    const click = name => button(name).click();
    const dialog = page.getByRole('dialog');
    await page.goto(url);
    await page.getByRole('heading',{name:'Task board',exact:true}).waitFor();
    for (const width of [1280,390]) {
      await page.setViewportSize({width,height:844});
      const mark = await page.locator('.brand .mark').boundingBox();
      const toggle = await button('中文').boundingBox();
      assert.ok(mark && toggle && mark.x+mark.width<=toggle.x);
      assert.ok(Math.abs((mark.y+mark.height/2)-(toggle.y+toggle.height/2))<2);
    }
    const purpose = await page.locator('[data-board-note]').innerText();
    await click('Guide');
    let core = page.locator('.guide-page section').first();
    assert.equal(await core.locator('h2').innerText(),'Core design');
    assert.equal(await core.locator('h3').count(),4);
    assert.equal(await core.locator('.guide-intro').innerText(),purpose);
    await click('Board');
    await click('中文');
    await page.getByRole('heading',{name:'任务棋盘',exact:true}).waitFor();
    assert.equal(await page.locator('html').getAttribute('lang'),'zh-CN');
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    const purposeZh = await page.locator('[data-board-note]').innerText();
    await click('使用指南');
    core = page.locator('.guide-page section').first();
    assert.equal(await core.locator('h2').innerText(),'核心设计');
    assert.equal(await core.locator('h3').count(),4);
    assert.equal(await core.locator('.guide-intro').innerText(),purposeZh);
    await page.getByRole('heading',{name:'抽选规则'}).waitFor();
    await click('更新');
    await page.getByText(/脚本计算棋盘指标/).waitFor();
    await click('统计');
    await page.getByLabel('活动图表').selectOption('calendar');
    await page.getByRole('heading',{name:'每日活动'}).waitFor();
    await button('怎样解读「完成情况」').click();
    await page.locator('#tip-total').getByText(/提前收工/).waitFor();
    await page.keyboard.press('Escape');
    await click('新建棋盘');
    await dialog.getByLabel('棋盘名称').fill('Board');
    await click('创建棋盘');
    await click('开始摆盘');
    await page.locator('[data-library="daily"][data-slot="0"]').click();
    await dialog.getByText('写个项目名就够了。今天你想给哪件事多一点机会？').waitFor();
    assert.equal(await dialog.getByLabel('任务名称').getAttribute('placeholder'),'例如：写论文');
    await dialog.getByLabel('任务名称').fill('Stats');
    await dialog.getByText('任务备注（选填）').click();
    await dialog.getByLabel('备注内容').fill('保留原文 {0} <Guide>');
    await click('保存任务');
    await page.locator('.libcell.selected').waitFor();
    await page.locator('[data-cell="0"]').click();
    await page.locator('[data-cell="0"]').getByText('Stats',{exact:true}).waitFor();
    await click('开始本轮'); await click('抽一项任务');
    await click('查看任务备注');
    await dialog.getByText('保留原文 {0} <Guide>',{exact:true}).waitFor();
    await click('关闭');
    await click('任务步骤');
    await dialog.getByLabel('步骤 1 的名称',{exact:true}).fill('Step one');
    await click('保存步骤');
    await dialog.waitFor({state:'hidden'});
    await page.reload();
    await page.getByRole('heading',{name:'任务棋盘'}).waitFor();
    await page.getByLabel('当前棋盘').selectOption({label:'Board'});
    await page.locator('[data-cell="0"]').click();
    await click('任务步骤');
    await button('步骤 1，Step one').click();
    await click('完成这一步'); await click('确认完成');
    await dialog.getByText('已完成 1 / 1 步').waitFor();
    await click('关闭');
    await click('English');
    await page.getByRole('heading',{name:'Task board'}).waitFor();
    await page.locator('[data-cell="0"]').getByText('Stats',{exact:true}).waitFor();
    await click('View task note');
    await dialog.getByText('保留原文 {0} <Guide>',{exact:true}).waitFor();
    await click('Close');
    await click('中文');
    await click('完成任务');
    await dialog.getByRole('button',{name:'完成任务',exact:true}).click();
    await dialog.waitFor({state:'hidden'});
    await click('统计');
    await page.getByText('未分类',{exact:true}).first().waitFor();
    await page.getByText('完成记录',{exact:true}).click();
    const entry = page.locator('details[open] .textlist li span').first();
    assert.equal(await entry.evaluate(el=>el.firstChild.textContent),'Stats');
    assert.deepEqual(errors,[]);
  } finally { await context.close(); }
}
